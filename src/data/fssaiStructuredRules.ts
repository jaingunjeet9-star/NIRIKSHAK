// Helper to lookup rules by canonical parameter and category
export function findStructuredRules(canonicalParam: string, category: string): StructuredFSSAIRule[] {
  const normCat = (category || '').toUpperCase().trim();
  const matches = STRUCTURED_FSSAI_RULES.filter(r => r.canonicalParameter === canonicalParam);
  if (matches.length === 0) return [];

  // Priority 1: Exact category match
  const exact = matches.filter(r => r.foodCategory === normCat);
  if (exact.length > 0) return exact;

  // Priority 2: Health supplement / protein supplement cross-match
  if (normCat.includes('PROTEIN') || normCat.includes('SUPPLEMENT') || normCat.includes('NUTRACEUTICAL') || normCat.includes('WHEY')) {
    const supp = matches.filter(r => r.foodCategory === 'PROTEIN_SUPPLEMENT');
    if (supp.length > 0) return supp;
  }

  // Priority 3: General food / all categories
  const general = matches.filter(r => r.foodCategory === 'ALL_FOODS' || r.foodCategory === 'GENERAL_FOOD');
  if (general.length > 0) return general;

  return matches;
}
